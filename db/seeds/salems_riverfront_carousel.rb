ActiveRecord::Base.transaction do
  maker = Maker.find_or_initialize_by(slug: "chance")
  maker.update!(
    name: "Chance", kind: "company",
    body: "The NCA identifies Salem's 2001 carousel as Chance/New Carvings. This identifies the mechanism maker, not the individual volunteer carvers.\n\nSource: [NCA new-carvings census](https://carousels.org/USACensus/stdqueries/census-cNEW.html).\n"
  )

  types = entries.map { _1.fetch(:type, "Horse") }.uniq.to_h do |name|
    category = case name
    when "Horse" then "horse"
    when "Chariot" then "chariot"
    else "menagerie"
    end
    type = FigureType.find_or_initialize_by(slug: name.parameterize)
    type.update!(name:, category:)
    [ name, type ]
  end

  carousel = Carousel.find_or_initialize_by(slug: "salems-riverfront-carousel")
  existing_inventory = Figure.where(slug: entries.map { "#{carousel.slug}-#{_1.fetch(:name).parameterize}" })
  expected_slugs = seating.transform_values { "#{carousel.slug}-#{_1.fetch(:name).parameterize}" }
  # End displaced placements while their seats still fit the pre-restoration chart.
  Placement.current.where(figure: existing_inventory).or(Placement.current.where(seat: carousel.seats)).each do |placement|
    next if placement.seat.carousel_id == carousel.id && expected_slugs[placement.seat.code] == placement.figure.slug

    SeatAssignment.new(placement.seat, nil).save!
  end

  carousel.update!(
    name: "Salem's Riverfront Carousel", city: "Salem", region: "Oregon", country: "United States",
    venue: "Riverfront Park", status: "operating", maker:, year_built: 2001, year_opened: 2001,
    official_url: "https://www.salemcarousel.org/", wikipedia_url: nil,
    other_links: <<~MD,
      [Meet the Herd](https://www.salemcarousel.org/meettheherd)
      [NCA photo gallery](https://carousels.org/psp/Salem/)
      [Seating video](https://www.youtube.com/watch?v=YGSPO9XFu-8)
    MD
    sections_count: 12, rows_count: 3, rotation: "counterclockwise",
    body: <<~MD
      A volunteer-built wooden carousel in Riverfront Park at 101 Front St NE, Salem, Oregon. It opened on June 2, 2001.

      ## Community history

      Hazel Patton's 1996 visit to A Carousel for Missoula inspired the Salem project. Groundbreaking took place on June 14, 2000. Community volunteers carved and painted the figures.

      The NCA identifies the mechanism as Chance/New Carvings, built in 2001; this is not an individual carving credit.

      ## Documented inventory

      The official directory supplies 42 original figure profiles, two wagon profiles, 17 New Dream catalog/project figures, and Serendipity Salmon, the non-riding ring dispenser: 62 catalog records, not 62 occupied seats.

      Sponsors, source poses, known rings, first-ride dates, and individual stories are preserved on the figure pages. A first-ride date is not a carving date. Traveling Ambassador, reserve Ruby Rose, and seasonal Happy Holidays and Spring Charm have distinct roles.

      The history describes Mr. Hopkins, Sweet Pea, Emerald, Harriett, and Blackberry as additions. Other New Dream entries include works in progress; gallery inclusion does not prove installation or completion. Undated project descriptions are not treated as current status reports.

      The NCA's 2020 census entry reports 28 jumping horses and 6 standing horses. Those source-era totals are not the complete modern catalog and do not establish named placements.

      ## Seating evidence

      The NCA documents three rings. A continuous exterior pass in the linked ride video, approximately 1:27-1:41, shows twelve repeating outside positions, including the two small foals beside the wagons, and counterclockwise rotation. An adjacent revolution repeats that sequence. The video was uploaded October 29, 2022; that is not a verified filming date.

      The twelve-section chart is a visual reading of this footage, not a manufacturer's plan or a verified current survey. No fourteen-section assumption is used.

      The General is explicitly identified as the lead horse and an outside-ring stander by his official profile. Seat 1A uses the wiki's lead-figure convention, not a published seat number.

      Eric's saved assignments on October 24, 2026, based on the second linked video, supply 34 placed figures: 24 horses, 8 other animals, and 2 wagons. Chuck Wagon at 4A and Covered Wagon at 10A each span A-B. All 34 placements retain confirmed confidence as entered by Eric, not independently re-verified here.

      The chart is fully assigned, with 34 seats because the two spanning wagons each cover an additional grid position. The remaining 28 catalog figures retain their carousel assignment without an assigned seat.

      Official profile rings are retained as source-era information and can differ from this video-derived layout. The October 24 date records the review and saved assignments, not a filming date. This is not a verified current survey. Unplaced catalog figures are not necessarily spares, retired, or absent from the ride.

      Summary-card counts reflect these saved assignments, not an independently verified complete operating complement.

      ## Music and brass ring

      The NCA records a Johnson Style 163 band organ with MIDI. Serendipity Salmon dispenses brass rings and is equipment, not a passenger mount.

      ## Sources

      - [Official history](#{official}/about-us).
      - [Meet the Herd: profiles and New Dream catalog](#{official}/meettheherd).
      - [The General: lead horse and outside ring](#{official}/general).
      - [NCA Salem gallery](https://carousels.org/psp/Salem/).
      - [NCA new-carvings census](https://carousels.org/USACensus/stdqueries/census-cNEW.html).
      - [Exterior ride video, starting at 1:27](https://www.youtube.com/watch?v=rSIXxKsNcXA&t=87s): visual platform count and rotation, not named seat assignments.
      - [Video used for Eric's saved figure assignments](#{placement_source}): layout captured October 24, 2026; filming date and per-figure timestamps not established.
      - [Sponsorships](#{official}/sponsorships): January 2027 project-progress plans.
    MD
  )

  inventory = entries.to_h do |entry|
    name = entry.fetch(:name)
    observed_position = seating.find { |_code, attributes| attributes.fetch(:name) == name }
    role = if observed_position && name != "The General"
      entry[:type] == "Chariot" ? "Stationary passenger bench in Eric's video-derived layout." : "Passenger figure in Eric's video-derived layout; installation date not established."
    else
      entry.fetch(:role, "Catalog riding figure; exact seat not established.")
    end
    details = [
      "Salem's Riverfront Carousel inventory.",
      "Collection: #{entry.fetch(:collection)}.",
      "Role: #{role}",
      entry[:pose] && "Source pose: #{entry[:pose]}.",
      entry[:ring] && "Documented ring: #{entry[:ring]} (#{ { "Outside" => "A", "Middle" => "B", "Inside" => "C" }.fetch(entry[:ring])} row only, not a section number). This official profile information may differ from the video-derived layout.",
      entry[:first_ride] && "First ride: #{entry[:first_ride]}. This is not a carving date.",
      entry[:credit],
      entry.fetch(:description),
      observed_position && "Video-derived layout: wiki seat #{observed_position.first}. Rows spanned: #{observed_position.last.fetch(:rows_spanned, 1)}. Confidence: #{observed_position.last.fetch(:confidence, "confirmed") == "confirmed" ? "Confirmed, as entered by Eric" : "Best reading, not yet confirmed"}.",
      observed_position && "Placement source: Eric's saved assignments on October 24, 2026, based on [this video](#{placement_source}). The review date is not a verified filming date or a current survey.",
      "Source: [Official catalog#{entry[:source] == "meettheherd" ? "" : " profile"}](#{official}/#{entry.fetch(:source)}).",
      entry[:collection] == "New Dream" ? "Additional source: [Official history](#{official}/about-us)." : nil,
      entry[:additional_source] && "Additional source: [Official sponsorship plans](#{official}/#{entry[:additional_source]})."
    ].compact
    figure = Figure.find_or_initialize_by(slug: "#{carousel.slug}-#{name.parameterize}")
    figure.update!(
      name:, short_name: nil, carousel:, figure_type: types.fetch(entry.fetch(:type, "Horse")),
      mount: entry[:mount] || { "Jumper" => "jumper", "Stander" => "stander" }[entry[:pose]],
      sponsor: entry[:sponsor], carver: nil, year_carved: nil,
      description: entry.fetch(:description), body: "#{details.join("\n\n")}\n"
    )
    [ name, figure ]
  end

  carousel.seats.where.not(section: 1..carousel.sections_count, row: carousel.row_letters).destroy_all
  carousel.seats.each do |seat|
    expected_span = seating.fetch(seat.code, {}).fetch(:rows_spanned, 1)
    seat.update!(rows_spanned: 1) if seat.rows_spanned != expected_span && seat.rows_spanned != 1
  end
  carousel.fill_missing_seats
  seating.each do |code, entry|
    seat = carousel.seats.find_by!(Seat.parse_code(code))
    seat.update!(confidence: entry.fetch(:confidence, "confirmed"), rows_spanned: entry.fetch(:rows_spanned, 1))
    SeatAssignment.new(seat, inventory.fetch(entry.fetch(:name))).save!
  end
  carousel.seats.reload.each do |seat|
    seat.update!(state: "unknown", confidence: "best_reading") unless seating.key?(seat.code)
  end
end
